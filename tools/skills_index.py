"""Write docs/skills.md from the frontmatter of every SKILL.md in claude/skills and claude-web/skills."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def front(text: str) -> dict:
    m = re.match(r"---\n(.*?)\n---", text.replace("\r\n", "\n"), re.S)
    out, key = {}, None
    for line in (m.group(1).splitlines() if m else []):
        kv = re.match(r"^([A-Za-z_]+):\s*(.*)$", line)
        if kv:
            key, val = kv.group(1), kv.group(2).strip()
            out[key] = "" if val in (">", "|", ">-", "|-") else val.strip("\"'")
        elif key and line.startswith((" ", "\t")):
            out[key] = (out[key] + " " + line.strip()).strip()
    return out


def main():
    rows = []
    for base, where in (("claude/skills", "Claude Code"), ("claude-web/skills", "claude.ai")):
        for s in sorted((ROOT / base).glob("*/SKILL.md")):
            text = s.read_text(encoding="utf-8")
            f = front(text)
            head = re.search(r"^#\s+(.+)$", text, re.M)
            desc = re.split(r"(?<=[.!?])\s", f.get("description", "") or (head.group(1) if head else ""), maxsplit=1)[0]
            desc = desc.replace(" — ", ": ").replace("—", ", ")   # no em dashes in published text
            rows.append(f"| [{s.parent.name}](../{base}/{s.parent.name}/SKILL.md) | {where} | {desc} |")
    text = ("<!-- generated by tools/skills_index.py -->\n# Skills\n\n"
            "| Skill | Runs in | What it does |\n|---|---|---|\n" + "\n".join(rows) + "\n\n"
            "Skills I use but didn't write are listed in [THIRD-PARTY.md](../THIRD-PARTY.md).\n")
    with open(ROOT / "docs" / "skills.md", "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"docs/skills.md: {len(rows)} skills")


if __name__ == "__main__":
    main()
